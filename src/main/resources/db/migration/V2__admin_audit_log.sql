-- 管理台操作审计
--
-- 为什么放数据库而不是只写日志：日志随容器滚动丢失，而「谁在什么时候删了哪个客户端」
-- 是这类系统唯一能事后追责的证据。表只追加，不提供修改入口。
--
-- detail 用自由文本（如 "role=ROLE_USER, enabled=true"）而不是结构化字段：
-- 不同动作关注的字段差别很大，拆成列会立刻出现一堆恒为 NULL 的列。

CREATE TABLE IF NOT EXISTS admin_audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    actor varchar(255) NOT NULL,
    action varchar(64) NOT NULL,
    target varchar(255),
    detail varchar(1000),
    ip varchar(64),
    -- 用带时区的类型：Hibernate 6 把 Instant 默认映射为 timestamp with time zone，
    -- 写成不带时区的 timestamp 会让读出来的时间偏移 8 小时（Hibernate 不做隐式转换）
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id)
);

-- 审计页按时间倒序分页；没有索引时数据量一上来就是全表扫描 + 排序
CREATE INDEX IF NOT EXISTS idx_admin_audit_log_created_at
    ON admin_audit_log (created_at DESC);
